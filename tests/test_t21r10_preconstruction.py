# -- R10 world builder: runtime-compatible manifest (Requirement 1) ------

def _blind_spec() -> dict:
    text = "Spec Entity holds value alpha."
    source_blob = json.dumps({
        "source_id": "gk-spec-source", "source_title": "Spec Source",
        "publisher_or_collection": "spec", "revision_or_version": "v1",
        "text": "",
    }, sort_keys=True, ensure_ascii=False)
    source_hash = hashlib.sha256(source_blob.encode("utf-8")).hexdigest()
    return {
        "world": [{"entity_id": "gk-spec-entity", "name": "Spec Entity"}],
        "sources": [{
            "source_id": "gk-spec-source", "source_title": "Spec Source",
            "source_type": "reference", "source_uri_or_origin": "spec://",
            "publisher_or_collection": "spec", "license": "CC0-1.0",
            "revision_or_version": "v1",
            "retrieved_at_or_snapshot_date": "2026-01-01",
            "language": "en", "authority_class": "PRIMARY_REFERENCE",
            "freshness_class": "STATIC", "topic_tags": ["spec"],
            "content_hash": source_hash, "document_hash": source_hash,
        }],
        "chunks": [{
            "chunk_id": "gk-spec-source:spec:0", "source_id": "gk-spec-source",
            "section": "spec", "text": text,
            "ordinal": 0, "span": [0, len(text)],
            "metadata": {"fact_entity": "Spec Entity",
                         "fact_attribute": "holds", "fact_value": "alpha"},
            "content_hash": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        }],
    }


def test_r10_world_manifest_is_load_corpus_compatible() -> None:
    """Requirement 1 + 2: the world builder's manifest loads under the
    ACTUAL frozen runtime, and counts agree."""
    spec = _blind_spec()
    with tempfile.TemporaryDirectory(prefix="t21r10-world-load-") as tmp:
        output = Path(tmp) / "world"
        manifest = world_builder.materialize_world(spec, output)
        corpus = load_corpus(output)
        assert manifest["source_count"] == len(corpus.sources) == 1
        assert manifest["chunk_count"] == len(corpus.chunks) == 1
        for key in ("corpus_version", "snapshot_date", "source_count",
                    "chunk_count", "domains", "license_summary",
                    "file_checksums", "manifest_checksum"):
            assert key in manifest, key
        assert set(manifest["file_checksums"]) == {"sources.jsonl",
                                                   "chunks.jsonl"}


def test_r10_world_manifest_checksums_match_runtime_lf_policy() -> None:
    spec = _blind_spec()
    with tempfile.TemporaryDirectory(prefix="t21r10-world-sha-") as tmp:
        output = Path(tmp) / "world"
        manifest = world_builder.materialize_world(spec, output)
        for name, expected in manifest["file_checksums"].items():
            data = (output / name).read_bytes().replace(b"\r\n", b"\n")
            assert hashlib.sha256(data).hexdigest() == expected
        blob = json.dumps({key: value for key, value in manifest.items()
                           if key != "manifest_checksum"},
                          sort_keys=True, ensure_ascii=False)
        assert hashlib.sha256(blob.encode("utf-8")).hexdigest() == \
            manifest["manifest_checksum"]


