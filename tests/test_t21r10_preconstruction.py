def test_r9_manifest_schema_regression() -> None:
    """The exact T21R9 failure: an R9 construction-schema manifest
    (counts/files_sha256 without runtime keys) must fail the official
    preflight before any ledger exists, with zero holdout rows."""
    with tempfile.TemporaryDirectory(prefix="t21r10-r9reg-") as tmp:
        root, out_dir = _sealed_candidate(tmp)
        corpus_dir = root / "rag" / "gk_holdout_t21r10"
        manifest = json.loads((corpus_dir / "corpus_manifest.json").read_text(
            encoding="utf-8"))
        legacy_r9 = {
            "artifact": "T21R10_BLIND_CORPUS_MANIFEST",
            "counts": {"sources": manifest["source_count"],
                       "chunks": manifest["chunk_count"]},
            "files_sha256": dict(manifest["file_checksums"]),
            "runtime_rows_executed": 0,
        }
        (corpus_dir / "corpus_manifest.json").write_text(json.dumps(legacy_r9))
        report = official.preflight(root)
        assert report["status"] == "FAIL"
        assert any("corpus compatibility" in defect
                   for defect in report["defects"])
        assert report["ledger_written"] is False
        assert report["runtime_execution_count"] == 0
        assert not (out_dir / "evaluation_run_ledger.json").exists()
        assert not (out_dir / "raw_results.jsonl").exists()
        assert not (out_dir / "holdout_results.json").exists()


