def generate(total: int = TOTAL) -> list[dict]:
    rng = random.Random(42)
    seen: set[str] = set()
    out: list[dict] = []
    family_tries: dict[str, int] = {f.__name__: 0 for f in FAMILIES}
    MAX_TRIES_PER_FAMILY = 60
    while len(out) < total:
        # family round-robin: the family that has been attempted the least
        f = min(FAMILIES, key=lambda fn: (family_tries[fn.__name__],
                                          FAMILIES.index(fn)))
        if family_tries[f.__name__] >= MAX_TRIES_PER_FAMILY:
            # this family is exhausted; if everything is exhausted, stop
            if all(t >= MAX_TRIES_PER_FAMILY for t in family_tries.values()):
                break
            continue
        family_tries[f.__name__] += 1
        gen = f(rng, len(out))
        if gen is None:
            continue
        q, sol, final = gen
        if not q or not final:
            continue
        fpr = text_fingerprint(q)
        if fpr in seen:
            continue
        # independent re-verification of the rendered steps + boxed final
        bad = verify_lines(sol)
        target = math_response("\n".join(sol), final)
        if bad or "\\boxed{" not in target or not target.endswith(
                f"Final answer: \\boxed{{{final}}}"):
            continue
        if any(t in target for t in ("None", "nan", "inf")):
            continue
        if len(target) > 1600:
            continue
        seen.add(fpr)
        rec = {
            "id": make_id("t32-verified-drills-v1", f"{f.__name__}-{len(out)}", q),
            "source": "t32-verified-drills-v1",
            "license": "MIT",
            "domain": "mathematics",
            "subject": f.__name__.replace("fam_", "drill_"),
            "question": q,
            "answer": final,
            "answer_type": "numeric",
            "difficulty": 2,
            "target_response": target,
            "verification": "step_lines_reverified_and_boxed_checked",
        }
        out.append(rec)
    from collections import Counter
    print("drills:", len(out), dict(Counter(r["subject"] for r in out)))
    return out


def main() -> int:
    recs = generate(TOTAL)
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "verified_drills.jsonl"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for r in recs:
            f.write(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n")
    body = "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n"
                   for r in recs)
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    manifest = {
        "artifact": "T32_VERIFIED_DRILLS",
        "schema_version": "t32-mixture-v1",
        "n": len(recs),
        "families": [f.__name__ for f in FAMILIES],
        "verification": ("forward-computed chains; every rendered arithmetic "
                         "equality re-verified by an independent evaluator "
                         "(split-on-=, consecutive numeric segments must "
                         "agree); boxed final must equal the computed value; "
                         "fails dropped; target <= 1600 chars"),
        "target_contract": "math_response (Final answer: \\boxed{...})",
        "seed": 42,
        "records": path.as_posix(),
        "sha256": digest,
    }
    (OUT / "verified_drills_manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print("sha", digest[:12])
    return 0


