def fam_word_multi(rng, k):
    """A 4-step chain word problem (premature-answer / underderivation target)."""
    n0 = rng.randint(40, 240)
    if n0 % 4:
        n0 += 4 - n0 % 4
    sold = n0 // 4
    extra = rng.randint(15, 90)
    bags = rng.randint(10, 30)
    left = (n0 - sold + extra) % bags
    q = (f"A market has {n0} apples, sells exactly a quarter of them, then "
         f"receives {extra} more. All apples are packed into bags of {bags}. "
         f"How many apples are left over after packing?")
    kept = n0 - sold
    tot = kept + extra
    sol = [f"Sold = {n0} / 4 = {sold}",
           f"Kept = {n0} - {sold} = {kept}",
           f"After receiving: {kept} + {extra} = {tot}",
           f"Left over = {tot} mod {bags} = {left}"]
    return q, sol, str(left)


