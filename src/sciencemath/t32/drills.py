"""T32 Phase 4: machine-generated, programmatically verified math drills.

Every drill is generated by computing the answer chain FORWARD from seeded
parameters (seed 42), rendering explicit step lines; every rendered
arithmetic equality is then RE-verified independently by re-evaluating each
side, the boxed final must equal the computed final, and any drill whose
re-verification fails is dropped. Deterministic: the same file every run.

Targets follow the canonical T30 math contract (``Final answer: \\boxed{}``)
through ``math_response`` and sit inside the 1600-char math budget.

Diagnostic targeting (Phase 1 taxonomy): the adapter's measured failure modes
are plain-arithmetic slips (~17% of adapter-wrong math rows) and
reasoning-chain / underderivation errors (~77%). The drill families therefore
emphasize explicit calculation chains over single-step recall.
"""
