def fam_chain(rng, k):
    """3-term addition/subtraction chain, expanded step by step."""
    a, b, c = (rng.randint(15, 900) for _ in range(3))
    op1, op2 = rng.choice("+-"), rng.choice("+-")
    m1 = a + b if op1 == "+" else a - b
    final = m1 + c if op2 == "+" else m1 - c
    q = f"Calculate {a} {op1} {b} {op2} {c} left to right."
    sol = [f"{a} {op1} {b} = {fm(m1)}", f"{fm(m1)} {op2} {c} = {fm(final)}"]
    return q, sol, fm(final)


def fam_multichain(rng, k):
    """Two-step product chain: (a x b) +- c, explicit partial product."""
    a, b, c = rng.randint(12, 499), rng.randint(2, 60), rng.randint(10, 900)
    op = rng.choice("+-")
    p = a * b
    final = p + c if op == "+" else p - c
    q = f"Compute {a} × {b} {'+' if op == '+' else '-'} {c}."
    sol = [f"{a} × {b} = {fm(p)}",
           f"{fm(p)} {'+' if op == '+' else '-'} {c} = {fm(final)}"]
    return q, sol, fm(final)


