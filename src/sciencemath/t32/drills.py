def _pf(n: int) -> list[str]:
    out, d = [], 2
    v = n
    while d * d <= v:
        while v % d == 0:
            out.append(str(d))
            v //= d
        d += 1
    if v > 1:
        out.append(str(v))
    return out


def fam_gcd_lcm(rng, k):
    a, b = rng.randint(12, 96), rng.randint(12, 96)
    gg = math.gcd(a, b)
    lcm = a * b // gg
    want_gcd = rng.random() < 0.5
    if want_gcd:
        q = f"Find the greatest common divisor of {a} and {b}."
        sol = [f"Prime factors: {a} = {' × '.join(_pf(a))}",
               f"Prime factors: {b} = {' × '.join(_pf(b))}",
               f"GCD = product of the common prime factors = {gg}"]
        return q, sol, str(gg)
    q = f"Find the least common multiple of {a} and {b}."
    sol = [f"Prime factors: {a} = {' × '.join(_pf(a))}",
           f"Prime factors: {b} = {' × '.join(_pf(b))}",
           f"LCM = {a} × {b} / {gg} = {fm(lcm)}"]
    return q, sol, fm(lcm)


def fam_perm(rng, k):
    n = rng.randint(4, 7)
    r = rng.randint(2, min(4, n - 1))
    v = 1
    factors = " × ".join(str(t) for t in range(n, n - r, -1))
    q = f"How many ways can {r} distinct items be arranged, chosen from {n}?"
    if r == 1:
        sol = [f"Arrangements = {n}"]
        v = n
    else:
        v = math.perm(n, r)
        sol = [f"Arrangements = {n} × {n-1}{' × ' + str(n-2) if r >= 3 else ''}"
               f"{' × ' + str(n-3) if r >= 4 else ''} = {v}"]
    return q, sol, str(v)


def fam_prob(rng, k):
    succ = rng.randint(1, 5)
    tot = rng.choice([6, 8, 10, 12, 20])
    if succ >= tot:
        return None
    val = Fraction(succ, tot)
    q = (f"A spinner has {tot} equal sectors and {succ} of them are red. "
         f"What is the probability of landing on red (lowest terms)?")
    sol = [f"P(red) = favourable / total = {succ}/{tot} = "
           f"{val.numerator}/{val.denominator}"]
    return q, sol, f"{val.numerator}/{val.denominator}"


def fam_geometry(rng, k):
    kind = rng.choice(["rect", "tri", "box"])
    if kind == "rect":
        w, h = rng.randint(3, 25), rng.randint(3, 25)
        q = f"A rectangle has width {w} cm and height {h} cm. What is its area in square centimeters?"
        sol = [f"Area = width × height = {w} × {h} = {fm(w * h)}"]
        return q, sol, fm(w * h)
    if kind == "tri":
        b = rng.choice([6, 8, 10, 12, 14, 16])
        h = rng.randint(3, 20)
        if (b * h) % 2:
            h += 1
        if (b * h) % 2:
            return None
        a = b * h // 2
        q = f"A triangle has base {b} cm and height {h} cm. What is its area in square centimeters?"
        sol = [f"Area = base × height / 2 = {b} × {h} / 2 = {b * h} / 2 = {fm(a)}"]
        return q, sol, fm(a)
    w, d, h = (rng.randint(2, 12) for _ in range(3))
    q = f"A box has dimensions {w} cm × {d} cm × {h} cm. What is its volume in cubic centimeters?"
    sol = [f"Volume = {w} × {d} × {h} = {fm(w * d)} × {h} = {fm(w * d * h)}"]
    return q, sol, fm(w * d * h)


