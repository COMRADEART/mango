def _num(s: str):
    try:
        return float(s.replace(",", ""))
    except ValueError:
        return None


def _tolerant(v: float, c: float) -> bool:
    return abs(v - c) <= max(0.005 * max(1.0, abs(v)), 0.005)


def _plain_arith(seg: str) -> bool:
    return bool(seg.strip()) and seg != seg.strip("\\") and all(
        ch in "0123456789.+-*/() " for ch in seg)


def verify_lines(lines: list[str]) -> list[str]:
    """Independent re-verification of rendered equality chains.

    A line ``a op b = c = d`` is split on '='; each consecutive pair of
    segments must agree numerically when BOTH are pure arithmetic. Prose
    segments (letters, LCD(), P(x), words) are skipped. Returns violation
    strings (empty list = verified). The boxed final is checked separately
    against the composed target."""
    bad: list[str] = []
    for line in lines:
        segs = [s.strip() for s in line.split("=")]
        if len(segs) < 2:
            continue
        vals = [_num(s) for s in segs]
        for a, b in zip(vals, vals[1:]):
            if a is None or b is None:
                continue          # prose or symbolic segment; not a step check
            if not _tolerant(a, b):
                bad.append(line)
                break
    return bad


def fm(x: float) -> str:
    """Format a value compactly (int when integral, else short decimal)."""
    if abs(x - round(x)) < 1e-9:
        n = int(round(x))
        return f"{n:,}" if abs(n) >= 10000 else str(n)
    return f"{x.rstrip('0').rstrip('.') if isinstance(x, str) else x:g}"


def g(x) -> str:
    return f"{x:g}" if isinstance(x, float) else str(x)


