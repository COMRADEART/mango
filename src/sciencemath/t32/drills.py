def fam_two_digit_mult(rng, k):
    a, b = rng.randint(12, 99), rng.randint(11, 99)
    if a == b:
        b += 1
    v = a * b
    tens, units = b - b % 10, b % 10
    q = f"Compute {a} × {b}."
    sol = [f"{a} × {b} = {a} × {tens} + {a} × {units}",
           f"{a} × {tens} = {fm(a * tens)}",
           f"{a} × {units} = {fm(a * units)}",
           f"{fm(a * tens)} + {fm(a * units)} = {fm(v)}"]
    return q, sol, fm(v)


