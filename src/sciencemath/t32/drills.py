def fam_mean(rng, k):
    nums = [rng.randint(1, 100) for _ in range(4)]
    m = rng.randint(1, 100)
    x = m * 5 - sum(nums)
    if x < 1:
        return None
    q = (f"The mean of five numbers {nums[0]}, {nums[1]}, {nums[2]}, "
         f"{nums[3]}, and x is {m}. What is x?")
    tot = m * 5
    known = sum(nums)
    sol = [f"Required sum = mean × count = {m} × 5 = {tot}",
           f"Known sum = {' + '.join(str(n) for n in nums)} = {known}",
           f"x = {tot} - {known} = {x}"]
    return q, sol, str(x)


def fam_word_discount(rng, k):
    price = rng.choice([120, 240, 350, 480, 640, 750, 899, 1250])
    p = rng.choice([10, 15, 20, 25, 30])
    tax = rng.choice([0, 5, 8, 10])
    cut = price * p / 100
    after = price - cut
    final = after * (1 + tax / 100)
    q = (f"A jacket costs ${price}. It is discounted by {p}%, then sales tax "
         f"of {tax}% is added to the discounted price. What is the final "
         f"price in dollars?")
    sol = [f"Discount = {price} × {p}/100 = {fm(cut)}",
           f"Discounted price = {price} - {fm(cut)} = {fm(after)}",
           f"Tax = {fm(after)} × {tax}/100 = {fm(after * tax / 100)}",
           f"Final price = {fm(after)} + {fm(after * tax / 100)} = {fm(final)}"]
    return q, sol, fm(final)


